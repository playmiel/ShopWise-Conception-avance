-- V3 : module Ventes (US 1 a 3).
-- Une vente (SALES) contient une ou plusieurs lignes (SALE_LINES), une par produit.
-- Le nom et le prix unitaire du produit sont COPIES dans la ligne au moment de la vente :
-- modifier ensuite le catalogue ne doit pas reecrire l'historique ni le chiffre d'affaires.
CREATE TABLE sales (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date    TIMESTAMP(6)   NOT NULL,
    total_amount DECIMAL(12, 2) NOT NULL,
    CONSTRAINT ck_sales_total_amount CHECK (total_amount >= 0)
);

-- Liste des ventes triee par date decroissante (US 2)
CREATE INDEX idx_sales_sale_date ON sales (sale_date);

CREATE TABLE sale_lines (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id      BIGINT         NOT NULL,
    product_id   BIGINT         NOT NULL,
    product_name VARCHAR(100)   NOT NULL,
    quantity     INTEGER        NOT NULL,
    unit_price   DECIMAL(10, 2) NOT NULL,
    line_total   DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_sale_lines_sale FOREIGN KEY (sale_id) REFERENCES sales (id) ON DELETE CASCADE,
    -- Pas de cascade : un produit deja vendu ne peut pas etre supprime (-> HTTP 409)
    CONSTRAINT fk_sale_lines_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uq_sale_lines_sale_product UNIQUE (sale_id, product_id),
    CONSTRAINT ck_sale_lines_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sale_lines_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sale_lines_line_total CHECK (line_total >= 0)
);

-- Jointures produit <-> ventes (module Recommandations, controle avant suppression)
CREATE INDEX idx_sale_lines_product ON sale_lines (product_id);
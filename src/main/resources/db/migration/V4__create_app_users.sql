-- V4 : comptes utilisateurs de l'API (US 4 et 5).
-- Le mot de passe n'est jamais stocke en clair : hash BCrypt prefixe par l'algorithme ({bcrypt}...),
-- ce qui permettra de changer d'algorithme plus tard sans invalider les comptes existants.
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'MERCHANT', 'VIEWER'))
);